let currentLesson = 1;
let currentScene = 0;
let isPlaying = false;
let autoPlayInterval = null;

const playBtn = document.getElementById('playBtn');
const pauseBtn = document.getElementById('pauseBtn');
const nextBtn = document.getElementById('nextBtn');
const chineseText = document.getElementById('chineseText');
const englishHighlight = document.getElementById('englishHighlight');
const vocabList = document.getElementById('vocabList');
const lessonBtns = document.querySelectorAll('.lesson-btn');

function initLesson(lessonNum) {
    currentLesson = lessonNum;
    currentScene = 0;
    isPlaying = false;

    lessonBtns.forEach(btn => btn.classList.remove('active'));
    document.querySelector(`[data-lesson="${lessonNum}"]`).classList.add('active');

    displayVocabulary();
    displayScene();
}

function displayScene() {
    const lesson = lessons[currentLesson];
    if (!lesson) return;

    const scene = lesson.scenes[currentScene];
    if (!scene) {
        chineseText.textContent = "课程完成！";
        englishHighlight.textContent = "Lesson Complete!";
        return;
    }

    chineseText.textContent = scene.chinese;
    englishHighlight.innerHTML = scene.english;

    animateCharacters();
}

function displayVocabulary() {
    const lesson = lessons[currentLesson];
    vocabList.innerHTML = '';

    lesson.fullVocab.forEach(vocab => {
        const vocabItem = document.createElement('div');
        vocabItem.className = 'vocab-item';
        vocabItem.innerHTML = `
            <div class="vocab-chinese">🇨🇳 ${vocab.chinese}</div>
            <div class="vocab-english">🇬🇧 ${vocab.english}</div>
            <div class="vocab-definition">= ${vocab.definition}</div>
        `;
        vocabList.appendChild(vocabItem);
    });
}

function animateCharacters() {
    const robot = document.getElementById('robot');
    const ai = document.getElementById('ai');

    robot.style.animation = 'none';
    ai.style.animation = 'none';

    setTimeout(() => {
        robot.style.animation = 'float 3s ease-in-out infinite';
        ai.style.animation = 'float 3s ease-in-out infinite 1s';
    }, 10);
}

function nextScene() {
    const lesson = lessons[currentLesson];
    if (currentScene < lesson.scenes.length - 1) {
        currentScene++;
        displayScene();
    }
}

function prevScene() {
    if (currentScene > 0) {
        currentScene--;
        displayScene();
    }
}

function startAutoPlay() {
    isPlaying = true;
    playBtn.textContent = '⏹ 停止';

    autoPlayInterval = setInterval(() => {
        const lesson = lessons[currentLesson];
        if (currentScene < lesson.scenes.length - 1) {
            nextScene();
        } else {
            stopAutoPlay();
        }
    }, 4000);
}

function stopAutoPlay() {
    isPlaying = false;
    playBtn.textContent = '▶ 播放';
    clearInterval(autoPlayInterval);
}

playBtn.addEventListener('click', () => {
    if (isPlaying) {
        stopAutoPlay();
    } else {
        startAutoPlay();
    }
});

pauseBtn.addEventListener('click', () => {
    if (isPlaying) {
        stopAutoPlay();
    }
    prevScene();
});

nextBtn.addEventListener('click', () => {
    if (isPlaying) {
        stopAutoPlay();
    }
    nextScene();
});

lessonBtns.forEach(btn => {
    btn.addEventListener('click', (e) => {
        const lessonNum = parseInt(e.target.dataset.lesson);
        initLesson(lessonNum);
    });
});

// Keyboard shortcuts for navigation
document.addEventListener('keydown', (e) => {
    if (e.key === 'ArrowRight') nextScene();
    if (e.key === 'ArrowLeft') prevScene();
    if (e.key === ' ') {
        e.preventDefault();
        playBtn.click();
    }
});

initLesson(1);
